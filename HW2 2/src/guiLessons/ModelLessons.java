package guiLessons;

import java.sql.SQLException;
import database.Database;
import entityClasses.Lesson;
import entityClasses.LessonList;

/**
 * <p> Title: ModelLessons Class. </p>
 * 
 * <p> Description: Provides lesson validation and database operations for the lesson page.
 * Maintains an in-memory lesson list that is replaced when all lessons are read.
 *
 * The controller validates lessons before calling create or update; those
 * persistence methods do not perform validation themselves. Database operations
 * require the application's database connection to be open and propagate SQL
 * errors to the caller. </p>
 *
 * @author Ahmad El-Merhaby
 */

public class ModelLessons {
		/** Application database used for persistent lesson storage. */
		private static Database theDatabase = applicationMain.FoundationsMain.database;
		/** In-memory list maintained by successful writes and full-list reads. */
		private static LessonList lessons = new LessonList();

		/**
		 * Checks the lesson's text lengths in title, problem, solution, and
		 * experience order. The {@link Lesson} constructor trims text and converts
		 * null text values to empty strings before this validation.
		 *
		 * @param lesson the non-null lesson to validate
		 * @return the first validation error, or an empty string when the title
		 *         contains 1-100 characters, problem and solution each contain
		 *         1-2000 characters, and optional experience contains 0-2000 characters
		 */
		protected static String validateLesson(Lesson lesson) {
			if (!Lesson.isValidTitle(lesson.getTitle()))
				return "Enter a title that is between 1-100 characters";
			if (!Lesson.isValidProblem(lesson.getProblem()))
				return "Enter a problem that is between 1-2000 characters";
			if (!Lesson.isValidSolution(lesson.getSolution()))
				return "Enter a solution that is between 1-2000 characters";
			if (!Lesson.isValidExperience(lesson.getExperience()))
				return "Experience has max 2000 characters";

			return "";
		}
		/**
		 * Saves a lesson, assigns its database-generated ID to the supplied object,
		 * and adds it to the in-memory list.
		 *
		 * @param lesson the non-null, validated lesson to save; its current ID is ignored
		 * @return the ID generated by the database
		 * @throws SQLException if saving fails or no generated ID is returned
		 */
		protected static int createLesson(Lesson lesson) throws SQLException {
			int id = lesson.create(theDatabase);
			if(id == -1) return -1;
			lessons.addLesson(lesson);
			return id;
		}
		/**
		 * Reads a lesson directly from the database without changing the in-memory list.
		 *
		 * @param id the ID of the lesson to read
		 * @return the stored lesson, or {@code null} if the ID does not exist
		 * @throws SQLException if the database read fails
		 */
		protected static Lesson readLesson(int id) throws SQLException {
			return Lesson.read(theDatabase,id);
		}
		/**
		 * Reloads all saved lessons, ordered by ID, and replaces the in-memory list.
		 *
		 * @return the newly loaded list, which may be empty and is also retained by
		 *         this model; callers receive the same {@link LessonList} instance
		 * @throws SQLException if the database read fails
		 */
		protected static LessonList readLessons(int ownerId) throws SQLException {
			lessons = LessonList.readLessons(theDatabase, ownerId);
			return lessons;
		}
		/**
		 * Updates the database record matching the lesson's ID and, on success,
		 * replaces the matching in-memory entry if present. The ID is unchanged.
		 *
		 * @param lesson the non-null, validated lesson containing the ID and new values
		 * @return {@code true} if a database record was updated; {@code false} if
		 *         no matching record exists
		 * @throws SQLException if the database update fails
		 */
		protected static boolean updateLesson(Lesson lesson) throws SQLException {
			if (!lesson.update(theDatabase)) return false;
			lessons.updateLesson(lesson);
			return true;
		}
		/**
		 * Deletes the database record and, on success, removes its in-memory entry
		 * if present.
		 *
		 * @param id the ID of the lesson to delete
		 * @return {@code true} if a database record was deleted; {@code false} if
		 *         no matching record exists
		 * @throws SQLException if the database deletion fails
		 */
		protected static boolean deleteLesson(int id) throws SQLException {
			Lesson lesson = Lesson.read(theDatabase, id);
			if (lesson == null || !lesson.delete(theDatabase)) return false;
			lessons.removeLesson(id);
			return true;
		}
	
}
